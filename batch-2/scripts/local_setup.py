"""Configure an extracted Windows package; provision and migrate only local PostgreSQL."""

from __future__ import annotations

import os
import secrets
import socket
import subprocess
import sys
from collections.abc import Mapping
from pathlib import Path

from dotenv import dotenv_values, set_key

from app.services.report_definition_service import ReportDefinitionService
from app.source_config import ReportSourceConfig
from scripts.local_launcher import (
    AuthenticationFailure,
    LauncherError,
    PortState,
    classify_port,
    configured_port,
    load_local_environment,
    remove_non_runtime_secrets,
    run_preflight,
)
from scripts.local_preflight import database_target

ROOT = Path(__file__).resolve().parents[1]
ENTRA_KEYS = (
    "MICROSOFT_CLIENT_ID",
    "MICROSOFT_CLIENT_SECRET",
    "MICROSOFT_TENANT_ID",
    "MICROSOFT_REDIRECT_URI",
    "ALLOWED_MICROSOFT_DOMAIN",
)


class SetupError(RuntimeError):
    """A setup failure whose message contains no credentials."""


def local_environment(root: Path, base: Mapping[str, str]) -> dict[str, str]:
    environment, _ = load_local_environment(
        base, tuple(root / name for name in (".env", ".env.local", ".env.postgres.local"))
    )
    return environment


def configure_environment(root: Path, base: Mapping[str, str]) -> dict[str, str]:
    """Preserve supplied settings and create fresh loopback demo settings when absent."""
    path = root / ".env.local"
    environment = local_environment(root, base)
    if not path.exists():
        path.write_text("# Local configuration generated by setup.cmd; do not share.\n", "utf-8")
        connected = all(environment.get(key, "").strip() for key in ENTRA_KEYS)
        set_key(str(path), "QC_ENABLE_DEMO_AUTH", "false" if connected else "true")
        set_key(str(path), "QC_APP_PORT", environment.get("QC_APP_PORT", "8080"))
    if len(environment.get("NICEGUI_STORAGE_SECRET", "").strip()) < 32:
        if "NICEGUI_STORAGE_SECRET" in base:
            raise SetupError("The exported NICEGUI_STORAGE_SECRET must be at least 32 characters.")
        set_key(str(path), "NICEGUI_STORAGE_SECRET", secrets.token_urlsafe(48))
    return local_environment(root, base)


def free_postgres_port() -> int:
    for port in range(5434, 5444):
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as connection:
            exclusive = getattr(socket, "SO_EXCLUSIVEADDRUSE", None)
            if exclusive is not None:
                connection.setsockopt(socket.SOL_SOCKET, exclusive, 1)
            try:
                connection.bind(("127.0.0.1", port))
            except OSError:
                continue
            return port
    raise SetupError("No free local PostgreSQL port was found between 5434 and 5443.")


def run_step(command: list[str], root: Path, environment: Mapping[str, str], label: str) -> None:
    runtime = dict(environment)
    remove_non_runtime_secrets(runtime)
    completed = subprocess.run(command, cwd=root, env=runtime, check=False)
    if completed.returncode:
        raise SetupError(
            f"{label} failed. Review the error above; saved credentials were not reset."
        )


def prepare_database(root: Path, base: Mapping[str, str]) -> dict[str, str]:
    environment = local_environment(root, base)
    credential_path = root / ".env.postgres.local"
    database_url = environment.get("QC_DATABASE_URL", "").strip()
    configured = bool(database_url and "replace-me" not in database_url)
    if configured:
        target = database_target(database_url)
        if target.host not in {"localhost", "127.0.0.1", "::1"} or (
            target.database != "qc_automation"
        ):
            raise SetupError("setup.cmd only prepares the loopback qc_automation database.")
        runtime = dict(environment)
        remove_non_runtime_secrets(runtime)
        try:
            run_preflight(runtime)
            return environment
        except AuthenticationFailure as error:
            raise SetupError(
                "Database login failed. Check the saved port and credentials."
            ) from error
        except LauncherError as error:
            if "QC_DATABASE_URL" in base or not credential_path.is_file():
                raise SetupError(
                    "The configured local database is unavailable. Check its service."
                ) from error

    if "QC_DATABASE_URL" in base and not configured:
        raise SetupError("Remove the placeholder QC_DATABASE_URL from the process environment.")
    saved = dotenv_values(credential_path) if credential_path.is_file() else {}
    raw_port = saved.get("QC_POSTGRES_LOCAL_PORT")
    if credential_path.is_file() and not raw_port:
        raise SetupError("Saved PostgreSQL settings have no local port; review them before setup.")
    port = int(raw_port) if raw_port else free_postgres_port()
    version_path = root / "data" / "postgres-local" / "PG_VERSION"
    major = version_path.read_text("ascii").strip() if version_path.is_file() else "17"
    if not major.isdigit():
        raise SetupError("The existing PostgreSQL cluster version is invalid.")
    binary = Path(
        environment.get("PROGRAMFILES", environment.get("ProgramFiles", r"C:\Program Files"))
    )
    if not (binary / "PostgreSQL" / major / "bin" / "pg_ctl.exe").is_file():
        raise SetupError(f"Install PostgreSQL {major} binaries, then rerun setup.cmd.")
    print(f"Preparing the project PostgreSQL cluster on loopback port {port}...")
    run_step(
        [
            "powershell.exe",
            "-NoProfile",
            "-NonInteractive",
            "-ExecutionPolicy",
            "Bypass",
            "-File",
            str(root / "scripts" / "provision_user_postgres.ps1"),
            "-Port",
            str(port),
            "-PostgresMajorVersion",
            major,
        ],
        root,
        environment,
        "PostgreSQL provisioning",
    )
    environment = local_environment(root, base)
    runtime = dict(environment)
    remove_non_runtime_secrets(runtime)
    run_preflight(runtime)
    return environment


def setup(root: Path = ROOT, base: Mapping[str, str] | None = None) -> None:
    base = dict(os.environ if base is None else base)
    environment = configure_environment(root, base)
    if classify_port(configured_port(environment)) is PortState.QC_APP:
        raise SetupError("Close the running application before setup applies database migrations.")
    definitions = ReportDefinitionService.from_config(
        ReportSourceConfig(
            root / "report_templates" / "manifest.json",
            root / "Basic Questions for Report Review Tool.xlsx",
        )
    ).load()
    print(f"Verified {len(definitions.templates)} templates and the question workbook.")
    environment = prepare_database(root, base)
    print("Applying database migrations...")
    run_step(
        [sys.executable, "-m", "alembic", "upgrade", "head"],
        root,
        environment,
        "Database migration",
    )
    print("Setup complete. Run start.cmd to open the application.")


def main() -> int:
    try:
        setup()
    except (SetupError, LauncherError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1
    except Exception as error:
        print(f"ERROR: Setup failed ({type(error).__name__}); credentials hidden.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
